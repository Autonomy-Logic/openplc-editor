/**
 * The factory of the preview's live elements (`resources/sources/hmi/unit/hmi_preview_factory.h`): tables of widget
 * types the module creates without a build, one per widget library, generated from the library alone so it compiles
 * once for every project, and one for the project's widget blocks, joined by a dispatcher that numbers them in order.
 */
import type { HmiPreviewFactory } from '../../../../middleware/shared/ports/hmi-preview-types'
import type { HmiWidgetCatalog, HmiWidgetInfo } from '../lib/widget-catalog'

/** Properties every element has that the preview never sets live. */
const STRUCTURAL = new Set(['PARENT', 'FLOATING'])

/** How the preview sets a property live: as a number, as text, or not at all. */
export function setterKind(p: HmiWidgetInfo['properties'][number]): 'num' | 'str' | undefined {
  if (STRUCTURAL.has(p.name.toUpperCase())) return undefined
  if (p.kind === 'string') return 'str'
  return p.kind === 'number' || p.kind === 'bool' || p.kind === 'color' ? 'num' : undefined
}

/** One table of the factory: its widget types numbered from 0, and the C++ defining its functions. */
export interface PreviewFactoryTable {
  /** Suffix of the table's functions, `hmi_factory_create<symbol>` and the like. */
  symbol: string
  /** Widget types by upper-case name, numbered within the table, with their setters. */
  types: HmiPreviewFactory['types']
  source: string
}

/** A table as the dispatcher needs it. */
export type PreviewFactoryPart = Pick<PreviewFactoryTable, 'symbol' | 'types'>

/** The suffix of a library's table functions: its name with anything but letters, digits and `_` replaced. */
export const factorySymbol = (library: string): string => `__${library.replace(/[^A-Za-z0-9_]/g, '_')}`

/** C++ of a function body that ignores `names`, so a table without entries compiles without warnings. */
const unused = (...names: string[]): string[] => names.map((n) => `    (void)${n};`)

const byName = (a: HmiWidgetInfo, b: HmiWidgetInfo): number =>
  a.name.toUpperCase() < b.name.toUpperCase() ? -1 : a.name.toUpperCase() > b.name.toUpperCase() ? 1 : 0

/**
 * The table of `widgets`, numbered in name order, with one setter number per declared input the preview sets live.
 * Its source includes `include`, which declares the widgets in `namespace`.
 */
export function previewFactoryTable(
  widgets: readonly HmiWidgetInfo[],
  symbol: string,
  include: string,
  namespace: string,
): PreviewFactoryTable {
  const types = [...widgets].sort(byName)
  const blocks = new Map<string, number>()
  const blockOf = (name: string): number => {
    const key = name.toUpperCase()
    const known = blocks.get(key)
    if (known !== undefined) return known
    blocks.set(key, blocks.size)
    return blocks.size - 1
  }
  const setters = { num: new Map<string, number>(), str: new Map<string, number>() }
  const cases = { num: [] as string[], str: [] as string[] }
  const table: HmiPreviewFactory['types'] = {}
  const kinds: string[] = []
  types.forEach((info, type) => {
    const own: HmiPreviewFactory['types'][string]['setters'] = {}
    const its = new Set<number>()
    for (const p of info.properties) {
      const kind = setterKind(p)
      if (kind === undefined) continue
      const block = blockOf(p.declaredBy)
      its.add(block)
      const key = `${p.declaredBy.toUpperCase()}.${p.name.toUpperCase()}`
      let index = setters[kind].get(key)
      if (index === undefined) {
        index = setters[kind].size
        setters[kind].set(key, index)
        const member = `static_cast<${namespace}::${p.declaredBy.toUpperCase()} *>(element)->${p.name.toUpperCase()}`
        cases[kind].push(
          kind === 'num'
            ? `    case ${index}: { if (!hmi_factory_is(type, ${block})) return -1; auto &m = ${member}; m.set(static_cast<std::decay_t<decltype(m.get())>>(value)); return 0; }`
            : `    case ${index}: if (!hmi_factory_is(type, ${block})) return -1; ${member}.set(value); return 0;`,
        )
      }
      own[p.name.toUpperCase()] = { index, kind }
    }
    table[info.name.toUpperCase()] = { type, setters: own }
    kinds.push(
      `    case ${type}: return ${its.size > 0 ? [...its].map((b) => `block == ${b}`).join(' || ') : 'false'};`,
    )
  })
  const cls = (info: HmiWidgetInfo): string => `${namespace}::${info.name.toUpperCase()}`
  const source = [
    '/* Generated by the HMI build: widget types the preview creates at run time, for the preview. */',
    '#include <new>',
    '#include <type_traits>',
    '',
    ...(types.length > 0 ? [`#include "${include}"`, ''] : []),
    'namespace {',
    '/* Whether widget type `type` is or extends the block that declares setters of number `block`. */',
    'bool hmi_factory_is(int type, int block) {',
    '    switch (type) {',
    ...kinds,
    '    default: return false;',
    '    }',
    '}',
    '}  // namespace',
    '',
    `void *hmi_factory_create${symbol}(int type) {`,
    '    switch (type) {',
    ...types.map((info, type) => `    case ${type}: return new (std::nothrow) ${cls(info)}();`),
    '    default: return nullptr;',
    '    }',
    '}',
    '',
    `void hmi_factory_destroy${symbol}(int type, void *element) {`,
    '    switch (type) {',
    ...types.map((info, type) => `    case ${type}: delete static_cast<${cls(info)} *>(element); return;`),
    '    default: return;',
    '    }',
    '}',
    '',
    `int hmi_factory_set_num${symbol}(int type, void *element, int setter, double value) {`,
    ...unused('type', 'element', 'value'),
    '    switch (setter) {',
    ...cases.num,
    '    default: return -1;',
    '    }',
    '}',
    '',
    `int hmi_factory_set_str${symbol}(int type, void *element, int setter, const char *value) {`,
    ...unused('type', 'element', 'value'),
    '    switch (setter) {',
    ...cases.str,
    '    default: return -1;',
    '    }',
    '}',
    '',
  ].join('\n')
  return { symbol, types: table, source }
}

/**
 * The factory functions of `hmi_preview_factory.h`, routing each type to its table: the tables' types are numbered
 * one after another in the order given. Returns the source and the factory of every catalogue widget, each from the
 * table of the library the catalogue takes it from, or from the last table (the project's) when that has none.
 */
export function previewFactoryDispatch(
  parts: ReadonlyArray<PreviewFactoryPart & { library?: string }>,
  catalog: HmiWidgetCatalog,
): { source: string; factory: HmiPreviewFactory } {
  const offsets: number[] = []
  let next = 0
  for (const part of parts) {
    offsets.push(next)
    next += Object.keys(part.types).length
  }
  const routed: Array<[string, HmiPreviewFactory['types'][string]]> = []
  const project = parts.findIndex((p) => p.library === undefined)
  for (const [name, info] of catalog.widgets) {
    let at = parts.findIndex((p) => p.library === info.library && p.types[name] !== undefined)
    if (at < 0 && project >= 0 && parts[project].types[name] !== undefined) at = project
    if (at < 0) continue
    const own = parts[at].types[name]
    routed.push([name, { type: offsets[at] + own.type, setters: own.setters }])
  }
  const factory: HmiPreviewFactory = {
    types: Object.fromEntries(routed.sort(([, a], [, b]) => a.type - b.type)),
  }
  const range = (i: number): string => {
    const count = Object.keys(parts[i].types).length
    return `type >= ${offsets[i]} && type < ${offsets[i] + count}`
  }
  const route = (call: (symbol: string, local: string) => string, fallback: string): string[] => [
    ...parts.flatMap((part, i) =>
      Object.keys(part.types).length === 0 ? [] : [`    if (${range(i)}) ${call(part.symbol, `type - ${offsets[i]}`)}`],
    ),
    `    ${fallback}`,
  ]
  const source = [
    '/* Generated by the HMI build: the preview factory, routing each widget type to its table. */',
    '#include "hmi_preview_factory.h"',
    '',
    ...parts.flatMap((part) => [
      `void *hmi_factory_create${part.symbol}(int type);`,
      `void hmi_factory_destroy${part.symbol}(int type, void *element);`,
      `int hmi_factory_set_num${part.symbol}(int type, void *element, int setter, double value);`,
      `int hmi_factory_set_str${part.symbol}(int type, void *element, int setter, const char *value);`,
    ]),
    '',
    'void *hmi_factory_create(int type) {',
    ...route((s, t) => `return hmi_factory_create${s}(${t});`, 'return nullptr;'),
    '}',
    '',
    'void hmi_factory_destroy(int type, void *element) {',
    ...route((s, t) => `{ hmi_factory_destroy${s}(${t}, element); return; }`, '(void)element;'),
    '}',
    '',
    'int hmi_factory_set_num(int type, void *element, int setter, double value) {',
    ...route(
      (s, t) => `return hmi_factory_set_num${s}(${t}, element, setter, value);`,
      '(void)element; (void)setter; (void)value; return -1;',
    ),
    '}',
    '',
    'int hmi_factory_set_str(int type, void *element, int setter, const char *value) {',
    ...route(
      (s, t) => `return hmi_factory_set_str${s}(${t}, element, setter, value);`,
      '(void)element; (void)setter; (void)value; return -1;',
    ),
    '}',
    '',
  ].join('\n')
  return { source, factory }
}
