/**
 * The host-side manifest of a Runtime v4 HMI (`resources/sources/hmi/unit/hmi_access.h`): the tag table, each screen's
 * read and write lists and roles, the program MD5 and the frame period, as C data the runtime builds into its HMI
 * host. It holds no screen code.
 */
import type { HmiPageTags, HmiTag } from '../unit/generate-hmi-unit'

export interface HmiHostManifestInput {
  tags: readonly HmiTag[]
  pages: readonly HmiPageTags[]
  md5: string
  periodMs: number
}

/** Most tags and screens a wire message can name (u16 ids). */
export const HMI_HOST_IDS_MAX = 0xffff

const cString = (s: string): string => JSON.stringify(s)

const idList = (name: string, ids: readonly number[]): string =>
  `static const uint16_t ${name}[${Math.max(ids.length, 1)}] = {${ids.length > 0 ? ids.join(', ') : '0'}};`

/** `hmi_access.c`, or the reason it cannot be built. */
export function hmiHostManifestSource(
  input: HmiHostManifestInput,
): { ok: true; source: string } | { ok: false; error: string } {
  if (input.tags.length > HMI_HOST_IDS_MAX)
    return { ok: false, error: `${input.tags.length} PLC variables on screens; at most ${HMI_HOST_IDS_MAX}` }
  if (input.pages.length === 0) return { ok: false, error: 'the HMI has no screens' }
  const unresolved = input.tags.find((t) => t.address === null)
  if (unresolved) return { ok: false, error: `${unresolved.path} has no debug address in the compiled PLC program` }
  const lists = input.pages.flatMap((p, i) => [idList(`reads_${i}`, p.reads), idList(`writes_${i}`, p.writes)])
  const tagRows = input.tags.map(
    (t) => `    {${t.address?.arr ?? 0}u, ${t.address?.elem ?? 0}u, ${t.type}, ${t.maxLength}, ${cString(t.path)}},`,
  )
  const pageRows = input.pages.map(
    (p, i) =>
      `    {reads_${i}, ${p.reads.length}, writes_${i}, ${p.writes.length}, ${p.roles}}, /* ${p.name.replace(/\*\//g, '')} */`,
  )
  const source = [
    '/* Generated by the HMI build: the tags, screens and roles the Runtime v4 HMI host serves (hmi_access.h). */',
    '#include "hmi_access.h"',
    '',
    ...lists,
    '',
    `const hmi_access_tag_t hmi_access_tags[${Math.max(input.tags.length, 1)}] = {`,
    ...(tagRows.length > 0 ? tagRows : ['    {0u, 0u, 0, 0, ""},']),
    '};',
    `const int hmi_access_tag_count = ${input.tags.length};`,
    `const hmi_access_page_t hmi_access_pages[${input.pages.length}] = {`,
    ...pageRows,
    '};',
    `const int hmi_access_page_count = ${input.pages.length};`,
    `const char hmi_access_plc_md5[] = ${cString(input.md5)};`,
    `const uint32_t hmi_access_period_ms = ${input.periodMs}u;`,
    '',
  ].join('\n')
  return { ok: true, source }
}
