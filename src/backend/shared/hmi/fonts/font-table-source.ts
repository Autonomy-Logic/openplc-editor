/**
 * Font build step of the HMI: turns the vetted font files a build uses into the C font table the core links
 * against (`hmi_font_table` in `resources/sources/hmi/core/hmi_internal.h`). Faces the build leaves out are NULL,
 * and the core draws their text with a face that is present.
 */

import { DEFAULT_HMI_FONT_VARIANT, HMI_FONT_COUNT, type HmiFontVariant, vettedHmiFont } from './vetted-fonts'

export interface HmiFontBytes {
  id: number
  /** Defaults to DEFAULT_HMI_FONT_VARIANT. */
  variant?: HmiFontVariant
  bytes: Uint8Array
}

export class HmiFontError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'HmiFontError'
  }
}

const BYTES_PER_LINE = 32

async function sha256Hex(bytes: Uint8Array): Promise<string> {
  const digest = await globalThis.crypto.subtle.digest('SHA-256', bytes)
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('')
}

function byteArray(name: string, bytes: Uint8Array): string {
  const lines: string[] = [`static const unsigned char ${name}[${bytes.length}] = {`]
  for (let start = 0; start < bytes.length; start += BYTES_PER_LINE) {
    lines.push(bytes.subarray(start, start + BYTES_PER_LINE).join(',') + ',')
  }
  lines.push('};')
  return lines.join('\n')
}

/**
 * C source of the font table for `fonts`, each checked against its vetted copy. Throws HmiFontError for an id and
 * variant that is not a vetted font, a face given twice, variants mixed in one build, or bytes that differ from the
 * vetted file.
 */
export async function buildHmiFontTableSource(fonts: readonly HmiFontBytes[]): Promise<string> {
  const byId = new Map<number, Uint8Array>()
  const variants = new Set(fonts.map((font) => font.variant ?? DEFAULT_HMI_FONT_VARIANT))
  if (variants.size > 1) throw new HmiFontError('The fonts of one build must all be the same variant')
  for (const font of fonts) {
    const variant = font.variant ?? DEFAULT_HMI_FONT_VARIANT
    const vetted = vettedHmiFont(font.id, variant)
    if (!vetted) throw new HmiFontError(`Font id ${font.id} (${variant}) is not a bundled HMI font`)
    if (byId.has(font.id)) throw new HmiFontError(`Font id ${font.id} was given more than once`)
    const digest = await sha256Hex(font.bytes)
    if (digest !== vetted.sha256) throw new HmiFontError(`Font ${vetted.file} does not match the bundled copy`)
    byId.set(font.id, font.bytes)
  }
  const parts = ['/* Generated by the HMI build: font table. Do not edit. */', '#include "hmi_internal.h"', '']
  const entries: string[] = []
  for (let id = 0; id < HMI_FONT_COUNT; id++) {
    const bytes = byId.get(id)
    if (bytes) {
      parts.push(byteArray(`hmi_font_${id}`, bytes), '')
      entries.push(`hmi_font_${id}`)
    } else {
      entries.push('0')
    }
  }
  parts.push(
    `_Static_assert(HMI_FONTS == ${HMI_FONT_COUNT}, "font ids differ between the HMI build and the core");`,
    `const unsigned char *const hmi_font_table[HMI_FONTS] = {${entries.join(', ')}};`,
    '',
  )
  return parts.join('\n')
}
