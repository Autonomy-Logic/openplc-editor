/**
 * `hmi_config.h` of a baremetal HMI build: the static sizes of the HMI core and host for the board's panel. The core,
 * the unit and the host include it, so one header decides every buffer the firmware reserves for the HMI.
 */
import type { ResolvedHmiPanel } from '../../../../middleware/shared/utils/target-capabilities/hmi-panel'
import { HMI_STB_ARENA_BYTES, type HmiFontVariant } from '../fonts/vetted-fonts'

export interface HmiConfigHeaderOptions {
  /** Compiles the test-only display-list readout in (`openplc-cli compile --hmi-test-readout`). */
  testReadout?: boolean
}

/** Largest glyph bitmap, in pixels, a static build draws (`HMI_GLYPH_SCRATCH_BYTES`). */
export const HMI_GLYPH_SCRATCH_BYTES = 8192

/** Smallest touch target in screen units (`HMI_MIN_TOUCH_LU`). */
const MIN_TOUCH_LU = 28

/**
 * Input elements a frame may record for touch (`HMI_BOUNDS_MAX`): one and a half times the touch targets the screen
 * holds side by side, in steps of 16, at least 64.
 */
export function hmiBoundsCapacity(panel: ResolvedHmiPanel): number {
  const area = Math.floor(panel.width / panel.density) * Math.floor(panel.height / panel.density)
  const targets = Math.ceil((area * 3) / (2 * MIN_TOUCH_LU * MIN_TOUCH_LU))
  return Math.max(64, Math.ceil(targets / 16) * 16)
}

/** The header for `panel`, with the stb_truetype arena of the font variant the firmware carries. */
export function hmiConfigHeader(
  panel: ResolvedHmiPanel,
  fontVariant: HmiFontVariant,
  options: HmiConfigHeaderOptions = {},
): string {
  const lines = [
    '/* Generated by the HMI build: static sizes of the HMI for this board panel. */',
    '#ifndef HMI_CONFIG_H',
    '#define HMI_CONFIG_H',
    '',
    '#define HMI_STATIC_MEMORY 1',
    `#define HMI_DL_CAPACITY ${panel.displayListBytes}`,
    `#define HMI_GLYPH_CACHE_BYTES ${panel.glyphCacheBytes}`,
    `#define HMI_GLYPH_SCRATCH_BYTES ${HMI_GLYPH_SCRATCH_BYTES}`,
    `#define HMI_BAND_BYTES ${panel.bandBytes}`,
    `#define HMI_STB_ARENA_BYTES ${HMI_STB_ARENA_BYTES[fontVariant]}`,
    `#define HMI_BOUNDS_MAX ${hmiBoundsCapacity(panel)}`,
    `#define HMI_RASTER_ROW_MAX ${panel.width + 1}`,
    `#define HMI_PANEL_WIDTH ${panel.width}`,
    `#define HMI_PANEL_HEIGHT ${panel.height}`,
    `#define HMI_PANEL_DENSITY ${panel.density}`,
    `#define HMI_PANEL_TOUCH ${panel.touch ? 1 : 0}`,
    `#define HMI_PANEL_RGB565 ${panel.colorFormat === 'rgb565' ? 1 : 0}`,
    `#define HMI_PANEL_TOUCH_CAL ${panel.touch && panel.touchCalibration ? 1 : 0}`,
    ...(options.testReadout ? ['#define HMI_TEST_READOUT 1'] : []),
    '',
    '#endif',
    '',
  ]
  return lines.join('\n')
}
